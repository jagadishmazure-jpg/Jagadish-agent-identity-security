def files(t: Tenant) -> dict[str, object]:
    """Relative path -> JSON payload, in the shapes the live collectors write."""

    def page(items):
        return {"@odata.context": "synthetic", "value": items}

    out: dict[str, object] = {
        "graph/users.json": page(t.users),
        "graph/userRegistrationDetails.json": page(t.reg),
        "graph/groups.json": page(t.groups),
        "graph/applications.json": page(t.apps),
        "graph/servicePrincipals.json": page(t.sps),
        "graph/oauth2PermissionGrants.json": page(t.grants),
        "graph/roleDefinitions.json": page([{"id": v, "displayName": k, "isBuiltIn": True} for k, v in t.dir_defs.items()]),
        "graph/roleAssignmentScheduleInstances.json": page(t.dir_active),
        "graph/roleEligibilitySchedules.json": page(t.dir_eligible),
        "graph/conditionalAccessPolicies.json": page(t.ca),
        "arm/resourceContainers.json": {"data": t.containers},
        "arm/resources.json": {"data": t.resources},
        "arm/roleDefinitions.json": {
            "data": [
                {
                    "id": f"/providers/Microsoft.Authorization/roleDefinitions/{v}",
                    "type": "microsoft.authorization/roledefinitions",
                    "properties": {"roleName": k, "type": "BuiltInRole"},
                }
                for k, v in t.az_defs.items()
            ]
        },
        "arm/roleAssignments.json": {"data": t.az_assign},
        "arm/roleEligibilityScheduleInstances.json": {"value": t.az_eligible},
        "arm/federatedIdentityCredentials.json": t.mi_fics,
        "foundry/agents.json": {"data": t.agents},
    }
    for vault, secrets in t.vault_secrets.items():
        out[f"keyvault/{vault}.json"] = {"value": secrets}
    for slug, export in t.saas.items():
        out[f"saas/{slug}.json"] = export
    return out


def dumps(obj) -> str:
    return json.dumps(obj, indent=1, sort_keys=True) + "\n"


def write(root: Path = TENANT_DATA, check: bool = False) -> list[str]:
    """Write (or with check=True, compare) the tenant files and the ground truth. Returns stale paths."""
    t = build()
    payload = {str(root / k): dumps(v) for k, v in files(t).items()}
    payload[str(DATA / "ground-truth.json")] = dumps({"planted": sorted(t.truth, key=lambda x: (x["rule"], x["subject"]))})
    stale = []
    for path, text in payload.items():
        p = Path(path)
        if not p.exists() or p.read_text() != text:
            stale.append(str(p.relative_to(DATA.parent)))
            if not check:
                p.parent.mkdir(parents=True, exist_ok=True)
                p.write_text(text)
    if not check:
        known = {Path(p) for p in payload}
        for p in root.rglob("*.json"):
            if p not in known:
                p.unlink()
                stale.append(str(p.relative_to(DATA.parent)))
    return stale
