"""Synthetic tenant for the fictional Kestrel Ridge Mortgage, written as Microsoft Graph and Azure
Resource Manager shaped JSON (the same files the live collectors write), plus a separate ground-truth
file of planted risks used only by the metrics.

Everything is deterministic: a fixed seed for the bulk users and a fixed scan time, so the data in
`data/tenant/` can be regenerated byte for byte and drift-checked in CI (`idsec synth --check`).

IDs follow `00000000-0000-0000-KKKK-NNNNNNNNNNNN` (KKKK = object kind), so no real tenant, object or
role ID ever appears in the repository."""

