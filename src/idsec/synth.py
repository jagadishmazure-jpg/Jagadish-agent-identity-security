_counters: dict[str, int] = {}


def gid(kind: str) -> str:
    _counters[kind] = _counters.get(kind, 0) + 1
    return f"00000000-0000-0000-{KIND[kind]:04x}-{_counters[kind]:012x}"


def iso(days_ago: float) -> str:
    return (SCAN - timedelta(days=days_ago)).strftime("%Y-%m-%dT%H:%M:%SZ")


def unix(days_ago: float) -> int:
    return int((SCAN - timedelta(days=days_ago)).timestamp())


